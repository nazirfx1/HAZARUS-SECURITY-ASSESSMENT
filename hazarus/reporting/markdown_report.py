"""
HAZARUS Markdown Report
Markdown report generation with HAZARUS branding.
"""

import logging
from typing import Dict, Any
from datetime import datetime


class MarkdownReport:
    """Markdown report module with HAZARUS branding (Red, White, Black)."""

    def __init__(self):
        self.logger = logging.getLogger("hazarus.markdown_report")

    async def generate(self, assessment_data: Dict[str, Any]) -> str:
        """Generate Markdown report."""
        self.logger.info("Generating Markdown report")

        content = self._generate_markdown(assessment_data)
        return content

    def _generate_markdown(self, data: Dict[str, Any]) -> str:
        """Generate markdown content."""
        md = []

        # Header with HAZARUS branding
        md.append("# HAZARUS Security Assessment Report")
        md.append("")
        md.append(f"**Assessment ID:** {data.get('assessment_id', 'N/A')}")
        md.append(f"**Generated:** {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}")
        md.append(f"**Targets:** {', '.join(data.get('targets', []))}")
        md.append("")
        md.append("---")
        md.append("")

        # Executive Summary
        if 'executive_summary' in data:
            md.append("## Executive Summary")
            md.append("")
            md.append(data['executive_summary'])
            md.append("")
            md.append("---")
            md.append("")

        # Assessment Phases
        if 'phases' in data:
            for phase_name, phase_data in data['phases'].items():
                md.append(f"## {phase_name}")
                md.append("")

                # Status
                status = phase_data.get('status', 'N/A')
                status_emoji = "✅" if status == "completed" else "⚠️" if status == "warning" else "❌"
                md.append(f"**Status:** {status_emoji} {status}")
                md.append("")

                # Findings
                if 'findings' in phase_data:
                    md.append("### Findings")
                    md.append("")
                    for finding in phase_data['findings']:
                        severity = finding.get('severity', 'info')
                        emoji = self._severity_emoji(severity)
                        md.append(f"{emoji} **{finding.get('title', 'N/A')}**")
                        md.append(f"   {finding.get('description', 'N/A')}")
                        md.append("")

                # Technical Details
                if 'technical_details' in phase_data:
                    md.append("### Technical Details")
                    md.append("")
                    for key, value in phase_data['technical_details'].items():
                        md.append(f"- **{key}:** {value}")
                    md.append("")

                # Recommendations
                if 'recommendations' in phase_data:
                    md.append("### Recommendations")
                    md.append("")
                    for rec in phase_data['recommendations']:
                        md.append(f"- {rec}")
                    md.append("")

                md.append("---")
                md.append("")

        # Overall Statistics
        if 'statistics' in data:
            md.append("## Overall Statistics")
            md.append("")
            for key, value in data['statistics'].items():
                md.append(f"- **{key}:** {value}")
            md.append("")
            md.append("---")
            md.append("")

        # Footer
        md.append("---")
        md.append("")
        md.append("*Generated by HAZARUS Security Assessment Framework*")
        md.append("*Version 2.0.0*")
        md.append("")

        return "\n".join(md)

    def _severity_emoji(self, severity: str) -> str:
        """Get emoji for severity level."""
        severity_map = {
            'critical': '🔴',
            'high': '🟠',
            'medium': '🟡',
            'low': '🟢',
            'info': '🔵'
        }
        return severity_map.get(severity.lower(), '⚪')
