"""
HAZARUS PDF Report
PDF report generation.
"""

import logging
from typing import Dict, Any
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch


class PDFReport:
    """PDF report module."""

    def __init__(self):
        self.logger = logging.getLogger("hazarus.pdf_report")

    async def generate(self, assessment_data: Dict[str, Any]) -> bytes:
        """Generate PDF report."""
        self.logger.info("Generating PDF report")

        from io import BytesIO
        buffer = BytesIO()

        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=72, leftMargin=72, topMargin=72, bottomMargin=18)
        story = []
        styles = getSampleStyleSheet()

        # Custom styles
        title_style = ParagraphStyle(
            'CustomTitle',
            parent=styles['Heading1'],
            fontSize=24,
            textColor=colors.HexColor('#1a1a2e'),
            spaceAfter=30
        )

        heading_style = ParagraphStyle(
            'CustomHeading',
            parent=styles['Heading2'],
            fontSize=16,
            textColor=colors.HexColor('#16213e'),
            spaceAfter=12
        )

        # Title
        story.append(Paragraph("HAZARUS Security Assessment Report", title_style))
        story.append(Spacer(1, 12))

        # Assessment info
        info_data = [
            ["Assessment ID:", assessment_data.get('assessment_id', 'N/A')],
            ["Generated:", datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')],
            ["Target:", assessment_data.get('target', 'N/A')],
            ["Start Time:", assessment_data.get('start_time', 'N/A')],
            ["End Time:", assessment_data.get('end_time', 'N/A')],
        ]

        info_table = Table(info_data, colWidths=[2*inch, 4*inch])
        info_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1a1a2e')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 12),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
            ('BACKGROUND', (0, 1), (-1, -1), colors.beige),
            ('GRID', (0, 0), (-1, -1), 1, colors.black)
        ]))

        story.append(info_table)
        story.append(Spacer(1, 24))

        # Executive Summary
        story.append(Paragraph("Executive Summary", heading_style))
        story.append(Paragraph(assessment_data.get('executive_summary', 'No executive summary available.'), styles['Normal']))
        story.append(Spacer(1, 24))

        # Findings
        story.append(Paragraph("Findings", heading_style))

        findings = assessment_data.get("findings", [])
        for finding in findings:
            severity = finding.get("severity", "unknown")
            finding_data = [
                [Paragraph(f"<b>{finding.get('title', 'Untitled')}</b>", styles['Normal']), Paragraph(severity.upper(), styles['Normal'])],
                [Paragraph(f"Severity: {severity}", styles['Normal']), ""],
                [Paragraph(f"Description: {finding.get('description', '')}", styles['Normal']), ""]
            ]

            finding_table = Table(finding_data, colWidths=[4*inch, 2*inch])
            finding_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (0, 0), colors.HexColor('#e3f2fd')),
                ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                ('GRID', (0, 0), (-1, -1), 1, colors.black)
            ]))

            story.append(finding_table)
            story.append(Spacer(1, 12))

        # Recommendations
        story.append(Paragraph("Recommendations", heading_style))

        for rec in assessment_data.get("recommendations", []):
            story.append(Paragraph(f"• {rec}", styles['Normal']))

        # Footer
        story.append(Spacer(1, 36))
        story.append(Paragraph("Generated by HAZARUS Security Assessment Framework v2.0.0", styles['Normal']))
        story.append(Paragraph("Confidential - For authorized personnel only", styles['Normal']))

        doc.build(story)

        pdf_data = buffer.getvalue()
        return pdf_data
